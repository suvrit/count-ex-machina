#!/usr/bin/env python3
"""Typeset one short note per case: `make notes`.

Each counterexamples/<id>/case.tex becomes a standalone amsart note in the look
of the author's aiproofs papers: a title block and abstract, the case exactly as
the paper prints it (credits, context, statements as posed, refutation), the
paper appendices the case refers to, a section pointing to the case's code and
certificate in this repository, an AI-usage note and the acknowledgements.  The
notes are hosted under "Notes/Countexes" at https://suvrit.github.io/.

Nothing here is written by hand, so a note can never drift from its case: edit
the case.tex (or the appendix file) and rebuild.  Appendices are found, not
listed -- a case that cites a label defined in one of the paper's appendix
files gets that file, and so on transitively; a label defined only in another
case is resolved against that case's note with xr-hyper and links to it.  A
label that resolves nowhere is an error.

Output goes to tex/notes/, gitignored like tex/preview/.  With --copy-to DIR the
PDFs and an index.json describing them are copied to DIR (the website's
notes/countexes/), in ledger order.

    python tools/notes.py                     # every refuted case
    python tools/notes.py odonnell-matrix-conjecture
    python tools/notes.py --copy-to ../suvrit.github.io/notes/countexes

Stdlib only.
"""
from __future__ import annotations

import argparse
import datetime
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from tools.build import (  # noqa: E402
    ROOT, effective_credits, found_by_list, found_by_str, load_cases, refuted_in_order,
    tex_to_markdown,
)

TEX = ROOT / "tex"
NOTES_DIR = TEX / "notes"
REPO = "https://github.com/suvrit/count-ex-machina"
PAPER = "2608.29595"
# Where the PDFs are served; a reference into another note links there.
BASE_URL = "https://suvrit.github.io/notes/countexes/"

LABEL_RE = re.compile(r"\\label\{([^}]+)\}")
REF_RE = re.compile(r"\\(?:eq|page|auto)?ref\{([^}]+)\}")
INPUT_RE = re.compile(r"\\input\{([^}]+)\}")
COMMENT_RE = re.compile(r"(?m)(?<!\\)%.*$")
STATEMENT_RE = re.compile(r"(?m)^\\begin\{cxstatement\}\{([^}]+)\}")

LEVELS = {"exact": "exact arithmetic", "computer-assisted": "rigorous interval arithmetic"}

WRAPPER = r"""%% GENERATED by tools/notes.py from counterexamples/%(case)s -- edit the case, not this.
\documentclass[11pt]{amsart}
\pdfoutput=1
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\usepackage[letterpaper,margin=1in]{geometry}
\usepackage{microtype}
\usepackage{xcolor}
\usepackage[inline]{enumitem}
\usepackage[authoryear,round]{natbib}
%(xr)s\usepackage{hyperref}
\usepackage{cxcase}
\input{generated/metadata}
\AtBeginDocument{\let\cite\citep}
\hypersetup{colorlinks=true,linkcolor=red!60!black,citecolor=green!48!black,urlcolor=blue!60!black}
\setlist{nosep,leftmargin=*}
\Urlmuskip=0mu plus 2mu
\numberwithin{equation}{section}
\makeatletter
\patchcmd{\section}{\scshape}{\fontfamily{ppl}\bfseries\scshape\selectfont}{}{}
%% A note is one case: its \cxtitle is the note's title, so the heading the paper
%% prints is dropped, a \cxsubtitle becomes a \section, and the rules the paper
%% draws between cases are off.  Before the first \section, theorems and
%% equations number 1, 2, ... rather than 0.1, 0.2, ...
\@namedef{cx@sub@note}{section}
\renewcommand{\cxtitle}[1]{}
\renewcommand{\thetheorem}{\ifnum\c@section>\z@\thesection.\fi\arabic{theorem}}
\renewcommand{\theequation}{\ifnum\c@section>\z@\thesection.\fi\arabic{equation}}
\makeatother
\cxlevel{note}
\setlength{\cxsecrulewidth}{0pt}
%(externals)s
\begin{document}
\title[%(short)s]{%(title)s}
\author[Suvrit Sra]{Suvrit Sra\textsuperscript{\normalfont*}}
\thanks{*\,TU Munich, Dept.~of Mathematics, School of CIT; Garching, Germany.
  Email: \texttt{s.sra@tum.de}.}
\thanks{From the \emph{Count ex Machina} archive of counterexamples,
  \url{%(repo)s}, whose companion paper is \href{https://arxiv.org/abs/%(paper)s}{arXiv:%(paper)s}.}
\date{%(date)s}
\begin{abstract}
%(abstract)s
\end{abstract}
\maketitle

\input{../../counterexamples/%(case)s/case.tex}
%(appendix)s
\section*{Code and certificate}
%(code)s

\section*{AI usage}
%(aiusage)s

\section*{Acknowledgements}
The author (SS) thanks the Alexander von Humboldt (AvH) Foundation for their
generous support via a Humboldt Professorship in AI.

\bibliographystyle{plainnat}
\bibliography{references}
\end{document}
"""


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True).stdout.strip()


def tex_escape(s):
    """Plain text from case.json, made safe to typeset.  A $...$ span is kept as
    math, since some artifact descriptions name a symbol that way; everything
    outside one is escaped, so a bare 2^n prints as written."""
    subs = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
            "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    parts = s.split("$")
    if len(parts) % 2 == 0:  # an unpaired $ is text, not math
        parts = [s]
    return "".join(f"${p}$" if i % 2 else "".join(subs.get(ch, ch) for ch in p)
                   for i, p in enumerate(parts))


def strip_comments(text):
    return COMMENT_RE.sub("", text)


def appendix_files():
    """The paper's appendix files, in the paper's order, that a note may carry:
    every \\input after \\appendix in main.tex except a file that itself
    \\input's cases (09-additional, the appendix's list of dossiers)."""
    main = strip_comments((TEX / "main.tex").read_text())
    tail = main.split("\\appendix", 1)[1]
    files = []
    for name in INPUT_RE.findall(tail):
        path = TEX / f"{name}.tex"
        if path.exists() and not any("counterexamples/" in f
                                     for f in INPUT_RE.findall(strip_comments(path.read_text()))):
            files.append(name)
    return files


def labels_and_refs(text):
    text = strip_comments(text)
    labels = set(LABEL_RE.findall(text)) | {f"ctx:{r}" for r in STATEMENT_RE.findall(text)}
    refs = {r for group in REF_RE.findall(text) for r in group.split(",")}
    return labels, refs


def resolve(cases, errors):
    """case id -> (appendix files to carry, other notes to resolve against)."""
    appendix = {name: labels_and_refs((TEX / f"{name}.tex").read_text()) for name in appendix_files()}
    case_labels = {c["id"]: labels_and_refs((c["_dir"] / c.get("prose", "case.tex")).read_text()) for c in cases}
    plan = {}
    for c in cases:
        labels, refs = (set(x) for x in case_labels[c["id"]])
        carried, externals = [], []
        while True:
            missing = refs - labels
            added = [name for name, (defs, _) in appendix.items() if name not in carried and defs & missing]
            if not added:
                break
            for name in added:
                carried.append(name)
                labels |= appendix[name][0]
                refs |= appendix[name][1]
        for ref in sorted(refs - labels):
            owner = next((cid for cid, (defs, _) in case_labels.items() if cid != c["id"] and ref in defs), None)
            if owner is None:
                errors.append(f"case {c['id']}: \\ref{{{ref}}} is defined nowhere a note can reach")
            elif owner not in externals:
                externals.append(owner)
        order = appendix_files()
        plan[c["id"]] = (sorted(carried, key=order.index), externals)
    return plan


def long_date(iso):
    d = datetime.date.fromisoformat(iso)
    return f"{d.day} {d.strftime('%B %Y')}"


def case_commit(c, carried):
    """(sha, unix time, ISO date) of the last commit touching what the note is
    made of: the case directory and the appendix files it carries.  A note cites
    that commit and is dated by it, so it changes only when its case does and a
    rebuild of an unchanged case gives a byte-identical PDF."""
    paths = [str(c["_dir"].relative_to(ROOT))] + [f"tex/{name}.tex" for name in carried]
    line = git("log", "-1", "--format=%H %ct %cs", "--", *paths)
    if not line:
        sys.exit(f"error: case {c['id']} has no commit yet; commit it before building its note")
    sha, epoch, iso = line.split()
    return sha, epoch, iso


def abstract(c):
    results = c["results"]
    levels = {r["certificate_level"] for r in results}
    how = " or ".join(LEVELS[l] for l in sorted(levels))
    words = {1: "a statement", 2: "two statements", 3: "three statements", 4: "four statements"}
    what = words.get(len(results), f"{len(results)} statements")
    lines = [f"This note records {what} refuted in the \\emph{{Count ex Machina}} archive: "
             f"each is quoted as posed and answered by an explicit witness, and the archive "
             f"carries a certificate that recomputes the refutation by {how}."]
    for r in results:
        lines.append(f"\\par\\smallskip\\noindent\\emph{{Summary:}} {r['statement_tex'].strip()}\\ "
                     f"\\emph{{Certificate:}} {r['certificate_tex'].strip()}")
    return "\n".join(lines)


def code_section(c, sha):
    cid = c["id"]
    tree = f"{REPO}/tree/{sha}/counterexamples/{cid}"
    v = c.get("verify") or {}
    lines = [f"The case is the directory \\href{{{tree}}}{{\\path{{counterexamples/{cid}/}}}} of the "
             f"archive, at commit \\texttt{{{sha[:7]}}}.  Its \\path{{{v.get('python', 'verify.py')}}} "
             f"recomputes every refutation in this note using exact arithmetic or rigorous interval "
             f"enclosures, never floating-point evidence alone; it raises an error if any check fails "
             f"and otherwise writes the certificate below."]
    if v.get("sage"):
        sage = ", ".join(f"\\path{{{s}}}" for s in v["sage"])
        lines.append(f"Independent Sage interval cross-checks: {sage}.")
    lines.append("To rerun it:\n\\begin{verbatim}\n"
                 f"git clone {REPO}\ncd count-ex-machina/counterexamples/{cid}\n"
                 f"python {v.get('python', 'verify.py')}\n\\end{{verbatim}}")
    items = [f"\\item Theorem~\\ref{{{r['theorem_label']}}} (result \\texttt{{{r['id']}}}): "
             f"{LEVELS[r['certificate_level']]}." for r in c["results"]]
    items += [f"\\item \\path{{{a['file']}}}: {tex_escape(a['description'])}" for a in c.get("artifacts") or []]
    lines.append("\\begin{itemize}\n" + "\n".join(items) + "\n\\end{itemize}")
    return "\n".join(lines)


def aiusage(c):
    found = sorted({found_by_str(effective_credits(c, r)) for r in c["results"]})
    many = len(c["results"]) > 1
    return ("The credit line under the title records, for each statement, who posed it, who "
            "found its counterexample and when, and who formalized and audited it; the "
            f"counterexample{'s' if many else ''} here {'were' if many else 'was'} found by "
            f"{tex_escape('; '.join(found))}.  "
            "This note was assembled mechanically from the case's source in the archive by "
            "\\path{tools/notes.py}, written with Claude Code; its mathematics is exactly that "
            "of the archive at the commit cited above.")


def write_note(c, plan, sha, iso):
    carried, externals = plan[c["id"]]
    title = c["title_tex"]
    plain = c.get("title") or c["id"]
    fields = {
        "case": c["id"],
        "title": title,
        "short": title if len(plain) <= 60 else "A Count ex Machina note",
        "repo": REPO,
        "paper": PAPER,
        "date": long_date(iso),
        "abstract": abstract(c),
        "xr": "\\usepackage{xr-hyper}\n" if externals else "",
        # amsart keeps its table-of-contents indents as tocindent labels in the
        # .aux; imported from another note they arrive as label records where
        # \section expects a dimension, so they are dropped after the import.
        "externals": "".join(f"\\externaldocument{{{e}}}[{BASE_URL}{e}.pdf]\n" for e in externals)
        + ("\\makeatletter\\@for\\cx@n:={-1,0,1,2,3}\\do{\\expandafter\\let"
           "\\csname r@tocindent\\cx@n\\endcsname\\relax}\\makeatother\n" if externals else ""),
        "appendix": ("\\appendix\n" + "".join(f"\\input{{{name}}}\n" for name in carried)) if carried else "",
        "code": code_section(c, sha),
        "aiusage": aiusage(c),
    }
    path = NOTES_DIR / f"{c['id']}.tex"
    path.write_text(WRAPPER % fields)
    return path


def compile_note(path, epoch):
    # Compiled from tex/notes/, so cxcase.sty, generated/ and references.bib are
    # one level up; the trailing empty entry keeps the default search path.
    # SOURCE_DATE_EPOCH pins the PDF's embedded dates and /ID to the case's last
    # commit, so rebuilding an unchanged case gives a byte-identical PDF and the
    # website's copy changes only when the case does.
    env = {
        **os.environ,
        "TEXINPUTS": f"..{os.pathsep}{os.environ.get('TEXINPUTS', '')}",
        "BIBINPUTS": f"..{os.pathsep}{os.environ.get('BIBINPUTS', '')}",
        **({"SOURCE_DATE_EPOCH": epoch, "FORCE_SOURCE_DATE": "1"} if epoch else {}),
    }
    proc = subprocess.run(["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", path.stem],
                          cwd=NOTES_DIR, env=env, capture_output=True, text=True)
    log = (NOTES_DIR / f"{path.stem}.log").read_text(errors="replace") if (NOTES_DIR / f"{path.stem}.log").exists() else ""
    problems = [line for line in log.splitlines()
                if re.search(r"undefined|Undefined control|^! ", line) and "Rerun" not in line]
    return proc.returncode, problems


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("cases", nargs="*", help="case ids (default: every refuted case)")
    ap.add_argument("--copy-to", type=Path, help="copy the PDFs and index.json here")
    args = ap.parse_args()

    errors = []
    cases = refuted_in_order(load_cases(errors))
    if errors:
        sys.exit("error: the cases do not load; run `make check` first\n  " + "\n  ".join(errors))
    unknown = set(args.cases) - {c["id"] for c in cases}
    if unknown:
        sys.exit(f"error: no refuted case named {sorted(unknown)}")
    plan = resolve(cases, errors)
    if errors:
        sys.exit("error: " + "\n  ".join(errors))

    if git("status", "--porcelain", "--", "counterexamples", "tex"):
        print("warning: the tree has uncommitted changes, which the notes' cited commits lack",
              file=sys.stderr)

    chosen = [c for c in cases if not args.cases or c["id"] in args.cases]
    # A note resolving labels against another note builds after it.
    chosen.sort(key=lambda c: bool(plan[c["id"]][1]))
    NOTES_DIR.mkdir(parents=True, exist_ok=True)
    failed = []
    for c in chosen:
        sha, epoch, iso = case_commit(c, plan[c["id"]][0])
        if not git("branch", "-r", "--contains", sha):
            print(f"warning: {c['id']} cites {sha[:7]}, which is on no remote branch yet", file=sys.stderr)
        code, problems = compile_note(write_note(c, plan, sha, iso), epoch)
        status = "ok" if code == 0 and not problems else "FAILED"
        print(f"{status:6} {c['id']}" + "".join(f"\n         {p}" for p in problems[:5]))
        if status != "ok":
            failed.append(c["id"])
    if failed:
        sys.exit(f"error: {len(failed)} note(s) failed: {', '.join(failed)} (see tex/notes/*.log)")

    if args.copy_to:
        args.copy_to.mkdir(parents=True, exist_ok=True)
        index = []
        for c in cases:
            pdf = NOTES_DIR / f"{c['id']}.pdf"
            if not pdf.exists():
                sys.exit(f"error: {pdf.relative_to(ROOT)} missing; build every note before copying")
            shutil.copy2(pdf, args.copy_to / pdf.name)
            index.append({
                "id": c["id"],
                "title": tex_to_markdown(c["title_tex"], errors, c["id"]),
                "pdf": pdf.name,
                "code": f"{REPO}/tree/main/counterexamples/{c['id']}",
                "found_by": list({(f["model"], f["date"]): {"model": f["model"], "date": f["date"]}
                                  for r in c["results"]
                                  for f in found_by_list(effective_credits(c, r))}.values()),
                "posed_by": list(dict.fromkeys(
                    tex_to_markdown(effective_credits(c, r).get("posed_by", ""), errors, c["id"])
                    for r in c["results"])),
                "certificate_levels": list(dict.fromkeys(r["certificate_level"] for r in c["results"])),
                "results": [r["id"] for r in c["results"]],
                "appendix": bool(c.get("appendix")),
            })
        if errors:
            sys.exit("error: " + "\n  ".join(errors))
        (args.copy_to / "index.json").write_text(json.dumps(index, indent=2, ensure_ascii=False) + "\n")
        print(f"copied {len(index)} notes and index.json to {args.copy_to}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
